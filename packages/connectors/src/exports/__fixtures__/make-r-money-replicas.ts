export async function tdaWorkbook(rows: Row[] = TDA_ROWS): Promise<Uint8Array> {
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet("Transaction Detail by Account");
  for (const r of rows) ws.addRow(r);
  return new Uint8Array((await wb.xlsx.writeBuffer()) as ArrayBuffer);
}

